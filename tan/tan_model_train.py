# Train a tiny tan(x) regression model and export it for TFLM on the Arduino GIGA R1.
# Outputs: tan_model.tflite (for LiteRT on the Pi) and tan_model.h (for the Arduino sketch)

import numpy as np
import tensorflow as tf

np.random.seed(0)
tf.random.set_seed(0)

# tan blows up at +/- pi/2 (about 1.57), so train on a limited range
x = np.random.uniform(-1.2, 1.2, 2000).astype(np.float32)
y = (np.tan(x) + 0.05 * np.random.randn(2000)).astype(np.float32)

model = tf.keras.Sequential([
    tf.keras.layers.Input(shape=(1,)),
    tf.keras.layers.Dense(16, activation="relu"),
    tf.keras.layers.Dense(16, activation="relu"),
    tf.keras.layers.Dense(1),
])
model.compile(optimizer="adam", loss="mse", metrics=["mae"])
model.fit(x, y, epochs=300, batch_size=32, validation_split=0.2, verbose=0)

loss, mae = model.evaluate(x, np.tan(x), verbose=0)
print(f"MAE vs clean tan(x): {mae:.4f}")

# float32 TFLite model (simplest to use in the sketch)
converter = tf.lite.TFLiteConverter.from_keras_model(model)
tflite = converter.convert()
with open("tan_model.tflite", "wb") as f:
    f.write(tflite)
print(f"tan_model.tflite: {len(tflite)} bytes")

# C array header for the Arduino sketch
with open("tan_model.h", "w") as f:
    f.write("#pragma once\n")
    f.write("alignas(16) const unsigned char g_model[] = {\n")
    for i in range(0, len(tflite), 12):
        chunk = ", ".join(f"0x{b:02x}" for b in tflite[i:i + 12])
        f.write(f"  {chunk},\n")
    f.write("};\n")
    f.write(f"const int g_model_len = {len(tflite)};\n")
print("tan_model.h written")



print(model.predict(np.array([[0.5], [0.7], [1.1]]), verbose=0))

interp = tf.lite.Interpreter(model_content=tflite)
interp.allocate_tensors()
inp = interp.get_input_details()[0]
out = interp.get_output_details()[0]
print("input type:", inp["dtype"])
for v in [0.5, 0.7, 1.1]:
    interp.set_tensor(inp["index"], np.array([[v]], dtype=np.float32))
    interp.invoke()
    print(v, interp.get_tensor(out["index"])[0][0])

with open("tan_float_model.h", "w") as f:
    f.write("#pragma once\n")
    f.write("alignas(16) const unsigned char g_model[] = {\n")
    for i in range(0, len(tflite), 12):
        chunk = ", ".join(f"0x{b:02x}" for b in tflite[i:i + 12])
        f.write(f"  {chunk},\n")
    f.write("};\n")
    f.write(f"const int g_model_len = {len(tflite)};\n")
print(len(tflite), "bytes")

